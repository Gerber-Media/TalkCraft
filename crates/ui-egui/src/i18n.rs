//! Interface language: English (the strings in the code) or German. `tr` looks a string up in the
//! German table when German is active; strings without a translation stay English.

use std::collections::HashMap;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicBool, Ordering};

static GERMAN: AtomicBool = AtomicBool::new(false);

/// `setting` is "de", "en" or "auto" (the system's language).
pub fn set(setting: &str) {
    let de = match setting {
        "de" => true,
        "en" => false,
        _ => system_is_german(),
    };
    GERMAN.store(de, Ordering::Relaxed);
}

pub fn german() -> bool {
    GERMAN.load(Ordering::Relaxed)
}

/// LANG / LC_ALL / LC_MESSAGES, and on macOS the first preferred language (asked once).
fn system_is_german() -> bool {
    static ANSWER: OnceLock<bool> = OnceLock::new();
    *ANSWER.get_or_init(|| {
        for k in ["LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Some(v) = std::env::var_os(k).and_then(|v| v.into_string().ok()).filter(|v| !v.is_empty() && v != "C" && v != "POSIX") {
                return v.starts_with("de");
            }
        }
        #[cfg(target_os = "macos")]
        if let Ok(out) = std::process::Command::new("defaults").args(["read", "-g", "AppleLanguages"]).output() {
            let text = String::from_utf8_lossy(&out.stdout);
            let first =
                text.split(['"', ',', '(', '\n', ' ']).find(|t| !t.trim().is_empty() && t.chars().all(|c| c.is_ascii_alphanumeric() || c == '-'));
            return first.is_some_and(|l| l.starts_with("de"));
        }
        false
    })
}

/// `s` in the active language.
pub fn tr(s: &str) -> &str {
    if !german() {
        return s;
    }
    match table().get(s) {
        Some(t) => t,
        None => {
            note_missing(s);
            s
        }
    }
}

/// `template` in the active language with each `{}` replaced by the next of `args`, in order
/// (the German template keeps the same number of `{}`).
pub fn trf(template: &str, args: &[&dyn std::fmt::Display]) -> String {
    let t = tr(template);
    let mut out = String::with_capacity(t.len() + 16);
    let mut args = args.iter();
    let mut rest = t;
    while let Some(i) = rest.find("{}") {
        out.push_str(rest.get(..i).unwrap_or(""));
        if let Some(a) = args.next() {
            out.push_str(&a.to_string());
        }
        rest = rest.get(i + 2..).unwrap_or("");
    }
    out.push_str(rest);
    out
}

/// Strings asked for in German without a translation, while recording (tests: `record_missing`).
static MISSING: std::sync::Mutex<Option<std::collections::BTreeSet<String>>> = std::sync::Mutex::new(None);

fn note_missing(s: &str) {
    if let Ok(mut m) = MISSING.lock()
        && let Some(set) = m.as_mut()
        && s.chars().any(char::is_alphabetic)
    {
        set.insert(s.to_string());
    }
}

/// Starts collecting untranslated strings (for the completeness test).
pub fn record_missing() {
    if let Ok(mut m) = MISSING.lock() {
        m.get_or_insert_with(Default::default);
    }
}

/// The untranslated strings seen since `record_missing`.
pub fn missing() -> Vec<String> {
    MISSING.lock().ok().and_then(|m| m.as_ref().map(|s| s.iter().cloned().collect())).unwrap_or_default()
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| DE.iter().copied().collect())
}

